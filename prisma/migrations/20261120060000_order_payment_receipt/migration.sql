CREATE TABLE "OrderPaymentReceipt" (
    "orderId" TEXT NOT NULL PRIMARY KEY REFERENCES "Order"("id") ON DELETE CASCADE ON UPDATE CASCADE,
    "method" VARCHAR(16) NOT NULL CHECK ("method" IN ('TRANSFER', 'ON_DELIVERY', 'WOMPI')),
    "amountCOP" BIGINT NOT NULL CHECK ("amountCOP" >= 0),
    "confirmedAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
